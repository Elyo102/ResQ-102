/* ====================================================================
 *  source-text · קריאת מקור שאינה תלויה בסוף-שורה
 *
 *  ----------------------------------------------------------------
 *  למה הקובץ הזה קיים
 *  ----------------------------------------------------------------
 *
 *  ארבע מבדיקות המקור נכשלו אצל Codex ב-Windows ועברו אצלי בלינוקס.
 *  הקוד היה זהה. מה שהיה שונה הוא **סוף השורה**.
 *
 *  `git ls-files --eol` מראה `i/lf, w/crlf`: במאגר הקבצים שמורים עם
 *  `\n`, ובעץ העבודה ב-Windows הם נכתבים עם `\r\n`. בדיקה שמחפשת
 *  `'\n}\n'` בטקסט המקור לא תמצא דבר כשהקובץ על הדיסק הוא CRLF.
 *
 *  ⭐ והכשל הזה הוא מהסוג המסוכן: הבדיקה לא „טעתה". היא **הפסיקה
 *  לבדוק**. דפוס שאינו נמצא הוא מוטציה שלא רצה, וטענה שלא נבדקה.
 *  אילו היא הייתה מדווחת „עבר" במקום ליפול, איש לא היה יודע.
 *
 *  לכן כל קריאת מקור בבדיקות עוברת דרך כאן, ולא דרך `readFileSync`
 *  ישירות. הנרמול הוא על **מה שנקרא לזיכרון בלבד** — אף קובץ על
 *  הדיסק אינו משתנה, ו-`.gitattributes` אינו נדרש.
 * ==================================================================== */

import { readFileSync } from 'node:fs';

/**
 * מנרמל טקסט מקור לסופי-שורה של `\n`.
 *
 * מטפל בשלושת הסגנונות: CRLF (Windows), CR בודד (Mac היסטורי) ו-LF.
 * הסדר חשוב — קודם CRLF, אחרת ה-CR הבודד היה מפצל כל שורה פעמיים.
 */
export function normalizeSource(value) {
  if (typeof value !== 'string') {
    throw new TypeError('normalizeSource מקבל מחרוזת בלבד');
  }
  return value.replace(/\r\n/g, '\n').replace(/\r/g, '\n');
}

/** קורא קובץ מקור ומחזיר אותו מנורמל. זו הדרך היחידה לקרוא מקור בבדיקות. */
export function readSource(path) {
  return normalizeSource(readFileSync(path, 'utf8'));
}
