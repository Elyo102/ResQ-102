import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

export function browserPolicy(configuration) {
  if (!configuration || Object.keys(configuration).length !== 1 || typeof configuration.creationEnabled !== 'boolean') {
    throw new Error('Reserve creation policy must contain exactly one boolean creationEnabled');
  }
  return '// Generated by reserve-shift-policy-build.mjs; edit functions/reserve-shift-policy.json only.\n'
    + `export const reserveShiftCreationEnabled = ${configuration.creationEnabled};\n`
    + 'export function canSelectReserveShift(savedType) {\n'
    + "  return reserveShiftCreationEnabled === true || savedType === 'reserve_shift';\n}\n";
}
export function checkPolicy() {
  const target = new URL('./reserve-shift-policy.js', import.meta.url);
  const expected = browserPolicy(JSON.parse(fs.readFileSync(new URL('./functions/reserve-shift-policy.json', import.meta.url), 'utf8')));
  if (fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== expected) throw new Error('Reserve browser/server policy drift');
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--write')) {
    fs.writeFileSync(new URL('./reserve-shift-policy.js', import.meta.url), browserPolicy(JSON.parse(fs.readFileSync(new URL('./functions/reserve-shift-policy.json', import.meta.url), 'utf8'))));
  } else checkPolicy();
  console.log('Reserve browser/server policy parity PASS');
}
